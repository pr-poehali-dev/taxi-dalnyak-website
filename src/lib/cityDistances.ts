function point(name: string): [number, number] | null {
  return C[ALIAS[name] ?? name] ?? null;
}

export function roadKm(a: string, b: string): number | null {
  const p = point(a);
  const q = point(b);
  if (!p || !q) return null;
  const rad = Math.PI / 180;
  const dLat = (q[0] - p[0]) * rad;
  const dLon = (q[1] - p[1]) * rad;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(p[0] * rad) * Math.cos(q[0] * rad) * Math.sin(dLon / 2) ** 2;
  const air = 2 * 6371 * Math.asin(Math.sqrt(h));
  const k = air < 300 ? 1.3 : air < 800 ? 1.18 : 1.15;
  return Math.round((air * k) / 10) * 10;
}

export function splitRoute(r: string): { from: string; to: string } | null {
  const i = r.indexOf(" – ");
  if (i < 0) return null;
  return { from: r.slice(0, i), to: r.slice(i + 3) };
}
