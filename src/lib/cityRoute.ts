function normalize(v: string): string {
  return v.toLowerCase().replace(/ё/g, "е").replace(/[^a-zа-я\s-]/gi, "").trim();
}

export function searchCities(query: string, limit = 8): string[] {
  const q = normalize(query);
  if (!q) return [];
  const starts: string[] = [];
  const inside: string[] = [];
  for (const city of ALL_CITIES) {
    const n = normalize(city);
    if (n.startsWith(q)) starts.push(city);
    else if (n.includes(q)) inside.push(city);
    if (starts.length >= limit) break;
  }
  return [...starts, ...inside].slice(0, limit);
}

export function roadKmBetween(from: string, to: string): number | null {
  const a = COORDS[from], b = COORDS[to];
  if (!a || !b) return null;
  return estimateRoadKm(a, b);
}

