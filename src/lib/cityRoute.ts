export interface RouteResult {
  from?: string;
  to?: string;
  km?: number;
  price?: { min: number; max: number };
}

export function parseRoute(termRaw: string): RouteResult | null {
  if (!termRaw) return null;
  let t = "";
  try { t = decodeURIComponent(termRaw); } catch { t = termRaw; }
  t = t.replace(/\+/g, " ").toLowerCase().trim();
  if (!t || t.startsWith("{") || t.endsWith("}")) return null;
  t = t.replace(/нижн\w*\s+новгород\w*/g, "нижний-новгород")
       .replace(/санкт\s*-?\s*петербург\w*/g, "санкт-петербург")
       .replace(/ростов\w*\s+на\s+дону/g, "ростов-на-дону")
       .replace(/минеральн\w*\s+вод\w*/g, "минеральные-воды")
       .replace(/[^a-zа-яё\s-]/gi, " ");

  const words = t.split(/\s+/).filter(Boolean);

  let fromCity: string | null = null;
  let toCity: string | null = null;

  for (let i = 0; i < words.length - 1; i++) {
    const w = words[i], next = words[i + 1];
    if (PREP_FROM.has(w) && !fromCity) { const c = toCityName(next); if (c) fromCity = c; }
    if (PREP_TO.has(w) && !toCity) { const c = toCityName(next); if (c) toCity = c; }
  }

  if (!fromCity || !toCity) {
    const found: string[] = [];
    for (const w of words) {
      if (SKIP.has(w) || PREP_FROM.has(w) || PREP_TO.has(w)) continue;
      const c = toCityName(w);
      if (c && !found.includes(c)) found.push(c);
    }
    if (!fromCity && found[0]) fromCity = found[0];
    if (!toCity) {
      const second = found.find(c => c !== fromCity);
      if (second) toCity = second;
    }
  }

  if (fromCity && toCity && fromCity !== toCity) {
    const a = COORDS[fromCity], b = COORDS[toCity];
    if (a && b) {
      const km = estimateRoadKm(a, b);
      const price = calcPrice(km, isNewTerritoriesRoute(fromCity, toCity));
      if (price) return { from: fromCity, to: toCity, km, price };
    }
    return { from: fromCity, to: toCity };
  }
  if (toCity) return { to: toCity };
  if (fromCity) return { from: fromCity };
  return null;
}