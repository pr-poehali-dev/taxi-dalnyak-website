export const ALL_CITIES: string[] = Object.keys(COORDS).sort((a, b) => a.localeCompare(b, "ru"));

export function getCoords(city: string): [number, number] | null {
  return COORDS[city] ?? null;
}

function normalize(v: string): string {
  return v.toLowerCase().replace(/ё/g, "е").replace(/[^a-zа-я\s-]/gi, "").trim();
}

export function searchCities(query: string, limit = 8): string[] {
  const q = normalize(query);
  if (!q) return [];
  const starts: string[] = [];
  const inside: string[] = [];
  for (const city of ALL_CITIES) {
    const n = normalize(city);
    if (n.startsWith(q)) starts.push(city);
    else if (n.includes(q)) inside.push(city);
    if (starts.length >= limit) break;
  }
  return [...starts, ...inside].slice(0, limit);
}

export function roadKmBetween(from: string, to: string): number | null {
  const a = getCoords(from), b = getCoords(to);
  if (!a || !b) return null;
  return estimateRoadKm(a, b);
}

const PREP_FROM = new Set(["из", "от", "с", "со"]);
const PREP_TO = new Set(["в", "во", "до", "на", "к", "ко"]);
const SKIP = new Set(["такси", "заказать", "заказ", "цена", "цену", "стоимость", "недорого", "дешево", "трансфер", "межгород", "межгородние", "поездка", "поездку"]);

function toCityName(word: string): string | null {
  return FORM_TO_CITY[word.toLowerCase().trim()] || null;
}

function haversineKm(a: [number, number], b: [number, number]): number {
  const R = 6371;
  const [lat1, lon1] = a, [lat2, lon2] = b;
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLon = (lon2 - lon1) * Math.PI / 180;
  const s = Math.sin(dLat / 2) ** 2 + Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
}

// Коэффициент извилистости дорог зависит от дальности:
// на коротких плечах трасса почти прямая, на дальних — заметно длиннее.
function roadFactor(straightKm: number): number {
  if (straightKm < 150) return 1.03;
  if (straightKm < 400) return 1.10;
  if (straightKm < 900) return 1.15;
  return 1.19;
}

function estimateRoadKm(a: [number, number], b: [number, number]): number {
  const straight = haversineKm(a, b);
  return Math.round((straight * roadFactor(straight)) / 10) * 10;
}

