export function findTown(slug: string): TownConfig | undefined {
  const t = TOWNS.find((x) => x.slug === slug);
  if (!t) return undefined;
  // убираем маршрут «город — сам в себя», если город попал в общий список направлений
  return { ...t, routes: t.routes.filter((r) => r.split(" – ")[1] !== t.city) };
}
